#!/usr/bin/env python3
"""Summarize a cpu_bench run directory into results/<run>/SUMMARY.md (medians, ranges, pass counts).

    python3 bench/summarize.py results/<run>
"""
import json
import os
import statistics as st
import sys
from collections import defaultdict


def fmt(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "-"
    if len(xs) == 1:
        return "%.2f" % xs[0]
    return "%.2f [%.2f-%.2f]" % (st.median(xs), min(xs), max(xs))


def main(d):
    runs = [json.loads(l) for l in open(os.path.join(d, "runs.jsonl"))]
    meta = json.load(open(os.path.join(d, "meta.json")))
    out = ["# Pilot summary: %s" % os.path.basename(d.rstrip("/")), "",
           "Generated by `bench/summarize.py` from `runs.jsonl`. Cells are median [min-max] over reps.",
           "Versions: %s. Model alias: %s. Load avg at start %s, end %s." % (
               ", ".join("%s %s" % kv for kv in meta["versions"].items()), meta["model_alias"],
               meta["machine"]["loadavg"], meta.get("machine_end", {}).get("loadavg")), ""]
    errs = [r for r in runs if "error" in r]
    h = defaultdict(list)
    for r in runs:
        if r["kind"] == "headless" and "error" not in r:
            h[(r["task"], r["harness"], r["profile"])].append(r)
    out += ["## Headless (`-p`) per task", "",
            "| task | harness | profile | pass | CPU s (rusage) | CPU s (tree) | wall s | peak RSS MB | procs |",
            "|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(h, key=lambda k: (["version", "pong", "stream", "tools"].index(k[0]), k[1], k[2])):
        rs = h[k]
        out.append("| %s | %s | %s | %d/%d | %s | %s | %s | %s | %s |" % (
            k[0], k[1], k[2], sum(r["ok"] for r in rs), len(rs), fmt([r["rusage_cpu_s"] for r in rs]),
            fmt([r["tree_cpu_s"] for r in rs]), fmt([r["wall_s"] for r in rs]),
            fmt([r["peak_tree_rss_mb"] for r in rs]), max(r["max_procs"] for r in rs)))
    i = defaultdict(list)
    for r in runs:
        if r["kind"] == "idle" and "error" not in r:
            i[(r["harness"], r["profile"])].append(r)
    out += ["", "## Interactive TUI (pty 120x40)", "",
            "| harness | profile | startup CPU s | idle %CPU | CPU s in 40 s after `stream` prompt | prompt pass | peak RSS MB |",
            "|---|---|---|---|---|---|---|"]
    for k in sorted(i):
        rs = i[k]
        out.append("| %s | %s | %s | %s | %s | %d/%d | %s |" % (
            k[0], k[1], fmt([r["startup_cpu_s"] for r in rs]), fmt([r["idle_cpu_pct"] for r in rs]),
            fmt([r.get("prompt_cpu_s") for r in rs]), sum(bool(r.get("prompt_ok")) for r in rs), len(rs),
            fmt([r["peak_tree_rss_mb"] for r in rs])))
    out += ["", "## Concurrency (`pong`, N started together)", "",
            "| harness | profile | N | all pass | total CPU s | CPU s per agent | batch wall s | sum peak RSS MB | load avg |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        if r["kind"] == "concurrent" and "error" not in r:
            out.append("| %s | %s | %d | %s | %.2f | %.2f | %.2f | %.0f | %.1f |" % (
                r["harness"], r["profile"], r["n"], r["all_ok"], r["sum_rusage_cpu_s"],
                r["sum_rusage_cpu_s"] / r["n"], r["batch_wall_s"], r["sum_peak_rss_mb"], r["loadavg"][0]))
    if errs:
        out += ["", "## Errors", ""] + ["- step %d %s %s %s: %s" % (r["i"], r["kind"], r["harness"], r["profile"], r["error"]) for r in errs]
    fails = [r for r in runs if r.get("ok") is False]
    if fails:
        out += ["", "## Failed checks", ""] + ["- step %d %s-%s %s rc=%s: %s" % (
            r["i"], r["harness"], r["profile"], r["task"], r.get("rc"), (r.get("stderr_tail") or r.get("stdout_tail") or "")[-160:].replace("\n", " ")) for r in fails]
    open(os.path.join(d, "SUMMARY.md"), "w").write("\n".join(out) + "\n")
    print(os.path.join(d, "SUMMARY.md"))


if __name__ == "__main__":
    main(sys.argv[1])
